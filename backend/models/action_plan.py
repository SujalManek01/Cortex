"""ActionPlan and ActionStep — the immutable execution plan produced by the Planner.

Engineering Rule 3: ActionPlans are immutable.
Engineering Rule 4: Execution state is separate (see execution_state.py).
"""
from __future__ import annotations

import uuid

from pydantic import BaseModel, ConfigDict, Field


class ActionStep(BaseModel):
    """A single action within an ActionPlan. Immutable once created.

    Engineering Rule 2: Every capability is an Action.
    The action field must use 'domain.verb' format (e.g. 'application.open').
    """

    model_config = ConfigDict(frozen=True)

    id: str = Field(description="Unique step identifier within this plan.")
    action: str = Field(
        description="Action identifier in 'domain.verb' format, e.g. 'application.open'."
    )
    parameters: dict[str, object] = Field(
        default_factory=dict,
        description="Action-specific parameters passed verbatim to the executor.",
    )


class ActionPlan(BaseModel):
    """Immutable execution plan. Produced by the Planner. Never mutated after creation.

    Refinement 1: created_by is assigned by the backend (StubPlanner), never the frontend.
    Refinement 2: plan_id is generated by the backend automatically.
    """

    model_config = ConfigDict(frozen=True)

    plan_id: uuid.UUID = Field(
        description="Backend-generated unique plan identifier (UUID v4)."
    )
    goal: str = Field(
        description="Natural language goal describing the user's intent."
    )
    version: str = Field(
        default="1.0",
        description="ActionPlan schema version. Only '1.0' is supported in Sprint 1.",
    )
    created_by: str = Field(
        description="Identifier of the planner that created this plan (e.g. 'stub_planner')."
    )
    steps: list[ActionStep] = Field(
        description="Ordered list of action steps to execute sequentially."
    )
