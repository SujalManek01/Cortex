"""StubPlanner — Sprint 1 pass-through planner.

Refinement 1: created_by is assigned by the backend (StubPlanner), never the frontend.
Refinement 2: plan_id is generated by the backend automatically (UUID v4).

The frontend sends only: { goal, steps: [{ action, parameters }] }
StubPlanner constructs the complete ActionPlan with a generated UUID, auto-incremented
step IDs, and a fixed created_by of "stub_planner".

StubPlanner does NOT subclass BasePlanner because it does not accept a raw natural
language goal as its only input — it requires pre-formed steps from the frontend.
BasePlanner is the interface for future LLM-backed planners.
"""
from __future__ import annotations

import uuid

from pydantic import BaseModel, Field

from backend.models.action_plan import ActionPlan, ActionStep


# ── Request models (what the frontend sends to POST /execute) ──────────────────

class ExecuteStepRequest(BaseModel):
    """A single step as submitted by the frontend.

    Deliberately excludes id — step IDs are generated by the backend.
    """

    action: str = Field(
        description="Action identifier in 'domain.verb' format, e.g. 'application.open'."
    )
    parameters: dict[str, object] = Field(
        default_factory=dict,
        description="Action-specific parameters for the executor.",
    )


class ExecuteRequest(BaseModel):
    """The execution request body submitted by the frontend via POST /execute.

    Deliberately excludes plan_id and created_by — both are backend concerns.
    The frontend owns: goal and steps.
    The backend owns: plan_id (UUID), created_by, step IDs, version.
    """

    goal: str = Field(
        description="Natural language description of the goal.",
        min_length=1,
    )
    steps: list[ExecuteStepRequest] = Field(
        description="Ordered list of action steps to execute.",
        min_length=1,
    )


# ── StubPlanner ────────────────────────────────────────────────────────────────

class StubPlanner:
    """Sprint 1 planner: converts an ExecuteRequest into a complete ActionPlan.

    Responsibilities:
    - Generate a UUID v4 for plan_id (Refinement 2).
    - Set created_by = "stub_planner" (Refinement 1).
    - Auto-assign step IDs as "step-1", "step-2", etc.
    - Set version = "1.0".
    - Return an immutable ActionPlan.

    Does NOT perform natural language understanding.
    """

    CREATED_BY: str = "stub_planner"
    VERSION: str = "1.0"

    def plan_from_request(self, request: ExecuteRequest) -> ActionPlan:
        """Convert an ExecuteRequest into an immutable ActionPlan.

        Args:
            request: The frontend-submitted execution request.

        Returns:
            ActionPlan with backend-generated plan_id and created_by.
        """
        steps = [
            ActionStep(
                id=f"step-{i + 1}",
                action=step.action,
                parameters=step.parameters,
            )
            for i, step in enumerate(request.steps)
        ]

        return ActionPlan(
            plan_id=uuid.uuid4(),
            goal=request.goal,
            version=self.VERSION,
            created_by=self.CREATED_BY,
            steps=steps,
        )
