/**
 * Cortex API client.
 * All calls go to the Vite dev proxy → FastAPI backend.
 */
import type {
  ExecuteRequest,
  ExecuteResponse,
  StatusResponse,
  ApplicationsResponse,
  FoldersResponse,
  WebsitesResponse,
  CapabilitiesResponse
} from '../types/cortex'

const BASE = ''  // Proxied via Vite to http://localhost:8000

async function handleResponse<T>(res: Response): Promise<T> {
  if (!res.ok) {
    const body = await res.json().catch(() => ({ message: res.statusText }))
    const detail = body.detail ?? body
    throw Object.assign(
      new Error(detail.message ?? `HTTP ${res.status}`),
      { status: res.status, detail }
    )
  }
  return res.json() as Promise<T>
}

/**
 * POST /execute — submit a plan for execution.
 * plan_id and created_by are generated by the backend.
 */
export async function executePlan(request: ExecuteRequest): Promise<ExecuteResponse> {
  const res = await fetch(`${BASE}/execute`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify(request),
  })
  return handleResponse<ExecuteResponse>(res)
}

/** GET /status — check if the engine is busy. */
export async function getStatus(): Promise<StatusResponse> {
  const res = await fetch(`${BASE}/status`)
  return handleResponse<StatusResponse>(res)
}

/** GET /health — liveness check. */
export async function getHealth(): Promise<{ status: string }> {
  const res = await fetch(`${BASE}/health`)
  return handleResponse<{ status: string }>(res)
}

export async function getApplications(): Promise<ApplicationsResponse> {
  const res = await fetch(`${BASE}/applications`)
  return handleResponse<ApplicationsResponse>(res)
}

export async function getFolders(): Promise<FoldersResponse> {
  const res = await fetch(`${BASE}/folders`)
  return handleResponse<FoldersResponse>(res)
}

export async function getWebsites(): Promise<WebsitesResponse> {
  const res = await fetch(`${BASE}/websites`)
  return handleResponse<WebsitesResponse>(res)
}

export async function getCapabilities(): Promise<CapabilitiesResponse> {
  const res = await fetch(`${BASE}/capabilities`)
  return handleResponse<CapabilitiesResponse>(res)
}
